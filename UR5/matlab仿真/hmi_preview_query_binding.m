function b=hmi_preview_query_binding(scene,request,binding,sceneSnapshotFile)
% Full provenance for request-local exact queries; never a reusable PASS.
here=fileparts(mfilename('fullpath')); root=fileparts(here); rrt=fullfile(fileparts(root),'RRT');
b=struct('realhome_version',request.realhome_version,...
    'qStart',reshape(request.qStart,1,6),'qHome',reshape(request.qHome,1,6),...
    'seed',request.seed,'calibration_binding',binding,...
    'scene_snapshot_sha256',hmi_workflow_file_hash(sceneSnapshotFile),...
    'self_collision_skip_pairs',{scene.selfCollisionSkipPairs},...
    'joint_limits',scene.jointLimits,'wire_collision_shorten_mm',3);
sources={fullfile(here,'replan_weld_actual_axis_adaptive_core.m'),...
    fullfile(here,'generate_actual_axis_ik_candidates.m'),fullfile(here,'refine_accp_cartesian_path.m'),...
    fullfile(here,'check_scene_environment_collision.m'),fullfile(rrt,'checkEnvironmentCollision.m'),...
    fullfile(rrt,'collisionFreeJointState.m'),fullfile(rrt,'collisionFreeJointEdge.m')};
b.collision_rule_sources=cell(1,numel(sources));
for k=1:numel(sources)
    b.collision_rule_sources{k}=struct('path',sources{k},'sha256',hmi_workflow_file_hash(sources{k}));
end
b.lifecycle='New instance per immutable scene/function; no cross-request cache';
end
