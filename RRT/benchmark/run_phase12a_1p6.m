function report = run_phase12a_1p6(options)
%run_phase12a_1p6 Calibrate 0.5-degree planning and 0.25-degree validation.
%
% This is the final small resolution-calibration gate before the 480-run
% Phase 12A-2 pilot. It keeps the Phase 12A-1 cases, seeds, and planner
% parameters unchanged.

if nargin < 1 || isempty(options), options=struct(); end
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
defaults=struct('outputFile',fullfile(root,'results','phase12a_resolution0p5deg_functional.mat'), ...
    'summaryFile',fullfile(root,'results','phase12a_resolution0p5deg_functional_summary.csv'), ...
    'validationOutputFile',fullfile(root,'results','phase12a_resolution0p5deg_validation0p25.mat'), ...
    'validationCsvFile',fullfile(root,'results','phase12a_resolution0p5deg_validation0p25.csv'), ...
    'validationWideCsvFile',fullfile(root,'results','phase12a_resolution0p5deg_validation0p25_wide.csv'), ...
    'maxIterations',300,'maxJointStepRad',deg2rad(25),'goalBias',0.20,'seed',1, ...
    'jointEdgeResolutionRad',deg2rad(0.5),'saveResult',true);
options=mergeOptions(defaults,options);
runner=struct('maxIterations',options.maxIterations,'maxJointStepRad',options.maxJointStepRad, ...
    'goalBias',options.goalBias,'seed',options.seed, ...
    'jointEdgeResolutionRad',options.jointEdgeResolutionRad, ...
    'saveResult',options.saveResult,'phase','Phase 12A-1.6', ...
    'archivalRerun',false,'outputFile',options.outputFile,'summaryFile',options.summaryFile);
report=run_phase12a_functional(runner);
report.plannerResolutionDeg=rad2deg(options.jointEdgeResolutionRad);
if options.saveResult, save(options.outputFile,'report','-v7.3'); end

validation=validate_phase12a_resolution(struct( ...
    'inputFile',options.outputFile,'outputFile',options.validationOutputFile, ...
    'csvFile',options.validationCsvFile,'wideCsvFile',options.validationWideCsvFile, ...
    'resolutionsDeg',0.25,'saveResult',options.saveResult));
report.validation=validation;
fprintf('PHASE12A1P6_DONE success=%d/%d validation025=%d/%d\n', ...
    sum([report.rows.success]),numel(report.rows),sum([validation.rows.pass]),numel(validation.rows));
end

function out=mergeOptions(defaults,in)
out=defaults; names=fieldnames(defaults);
for i=1:numel(names)
    if isfield(in,names{i}) && ~isempty(in.(names{i})), out.(names{i})=in.(names{i}); end
end
end
