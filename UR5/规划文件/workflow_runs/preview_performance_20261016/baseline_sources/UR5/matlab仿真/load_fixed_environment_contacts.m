function [policy,record]=load_fixed_environment_contacts(scene,root)
% Fail closed if an explicit support record no longer matches the REAL scene.
policy=[]; record=struct('status','NONE','sha256','','pair',{{}});
file=fullfile(root,'fixed_environment_contacts.json');
if ~isfile(file), return; end
p=jsondecode(fileread(file));
assert(strcmp(p.status,'ACTIVE_MODEL_VERIFIED_FIXED_SUPPORT') && ...
    strcmp(p.robot_body,'base_link_inertia') && ...
    strcmp(p.environment_object,'EnvironmentCollision_Floor'),...
    'FIXED_SUPPORT:Policy','Only the certified base-to-Floor support pair is allowed');
assert(strcmp(p.urdf_sha256,hmi_workflow_file_hash(fullfile(root,'real_robot_description_calibrated.urdf'))) && ...
    strcmp(p.environment_geometry_sha256,hmi_workflow_file_hash(fullfile(root,'environment_geometry_real.json'))),...
    'FIXED_SUPPORT:STALE','Support exception model/environment version changed');
links=scene.robotBodyCollisionLoad.links;
b=links{find(cellfun(@(x)strcmp(x.geometry_link,p.robot_body),links),1)};
assert(numel(b.mesh_sha256)==1 && strcmp(b.mesh_sha256{1},p.base_mesh_sha256),...
    'FIXED_SUPPORT:STALE','Support base collision mesh changed');
evidence=verify_fixed_base_floor_contact(scene);
assert(evidence.eligible,'FIXED_SUPPORT:Unverified','Base/floor no longer matches normal fixed support contact');
names=hmi_environment_names(scene);
policy=struct('status',evidence.status,'pair',{{p.robot_body,p.environment_object}},...
    'body_index',find(strcmp(scene.robot.BodyNames,p.robot_body)),...
    'environment_index',find(strcmp(names,p.environment_object)),...
    'floor_pose',evidence.floor_pose,'floor_size_m',evidence.floor_size_m,...
    'T_root_base_body',evidence.T_root_base_body);
record=struct('status','EXEMPT_FIXED_INSTALLATION_CONTACT','sha256',hmi_workflow_file_hash(file),...
    'file',file,'version',p.version,'pair',{policy.pair},'evidence',evidence,...
    'scope','One fixed base support pair only; all moving links, gun, wire and other environment pairs remain hard');
end
