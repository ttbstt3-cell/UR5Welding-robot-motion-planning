function report = run_phase12a_1p5(options)
%run_phase12a_1p5 Run 1-degree planning and 0.5-degree path validation.
%
% This is a small calibration stage, not the 480-run pilot. The planner is
% called only for the 24 functional cases. Validation then reads the saved
% qPaths and does not call any planner.

if nargin < 1 || isempty(options), options=struct(); end
here=fileparts(mfilename('fullpath'));
root=fileparts(here);
defaults=struct('outputFile',fullfile(root,'results','phase12a_resolution1deg_functional.mat'), ...
    'summaryFile',fullfile(root,'results','phase12a_resolution1deg_functional_summary.csv'), ...
    'validationOutputFile',fullfile(root,'results','phase12a_resolution1deg_validation05.mat'), ...
    'validationCsvFile',fullfile(root,'results','phase12a_resolution1deg_validation05.csv'), ...
    'validationWideCsvFile',fullfile(root,'results','phase12a_resolution1deg_validation05_wide.csv'), ...
    'comparisonFile',fullfile(root,'results','phase12a_resolution1deg_vs_2deg.csv'), ...
    'maxIterations',300,'maxJointStepRad',deg2rad(25),'goalBias',0.20,'seed',1, ...
    'jointEdgeResolutionRad',deg2rad(1),'saveResult',true);
options=mergeOptions(defaults,options);
runner=struct('maxIterations',options.maxIterations,'maxJointStepRad',options.maxJointStepRad, ...
    'goalBias',options.goalBias,'seed',options.seed, ...
    'jointEdgeResolutionRad',options.jointEdgeResolutionRad, ...
    'saveResult',options.saveResult,'phase','Phase 12A-1.5', ...
    'archivalRerun',false,'outputFile',options.outputFile,'summaryFile',options.summaryFile);
report=run_phase12a_functional(runner);
report.plannerResolutionDeg=rad2deg(options.jointEdgeResolutionRad);
if options.saveResult, save(options.outputFile,'report','-v7.3'); end

validationOptions=struct('inputFile',options.outputFile, ...
    'outputFile',options.validationOutputFile,'csvFile',options.validationCsvFile, ...
    'wideCsvFile',options.validationWideCsvFile,'resolutionsDeg',0.5, ...
    'saveResult',options.saveResult);
validation=validate_phase12a_resolution(validationOptions);
compare_phase12a_resolution1deg(struct('newFile',options.outputFile, ...
    'comparisonFile',options.comparisonFile));
report.validation=validation;
fprintf('PHASE12A1P5_DONE success=%d/%d validation05=%d/%d\n', ...
    sum([report.rows.success]),numel(report.rows),sum([validation.rows.pass]),numel(validation.rows));
end

function out=mergeOptions(defaults,in)
out=defaults; names=fieldnames(defaults);
for i=1:numel(names)
    if isfield(in,names{i}) && ~isempty(in.(names{i})), out.(names{i})=in.(names{i}); end
end
end
