function report = run_phase12a_2r_pilot(options)
%run_phase12a_2r_pilot Seam A 160-run fixed-time pilot.
%
% This entry point is intentionally separate from the historical C01-C06
% pilot.  It runs only the two real Seam A free-space tasks:
%   T01: qSafe(qHome) -> Point 1
%   T02: Point 80 -> qSafe(qHome)
% Use only after the 40-run 0.25/0.125 degree calibration is accepted.

if nargin < 1 || isempty(options), options=struct(); end
root=fileparts(fileparts(mfilename('fullpath')));
defaults=struct( ...
    'taskSet','seamA', ...
    'maxPlanningTimeSec',2.0, ...
    'maxIterations',300, ...
    'maxJointStepRad',deg2rad(25), ...
    'goalBias',0.20, ...
    'jointEdgeResolutionRad',deg2rad(0.25), ...
    'validationResolutionRad',deg2rad(0.125), ...
    'seeds',1:20, ...
    'bootstrapReplicates',1000, ...
    'outputFile',fullfile(root,'results','phase12a_2r_pilot_160.mat'), ...
    'rawCsvFile',fullfile(root,'results','phase12a_2r_pilot_160_runs.csv'), ...
    'summaryCsvFile',fullfile(root,'results','phase12a_2r_pilot_160_summary.csv'), ...
    'figureDir',fullfile(root,'results','phase12a_2r_pilot_160_figures'), ...
    'saveResult',true);
options=mergeLocal(defaults,options);
report=run_phase12a_pilot(options);
fprintf('PHASE12A2R_PILOT_DONE rows=%d plannerSuccess=%d validSuccess=%d timeouts=%d\n', ...
    report.completedRuns,sum([report.rows.success]), ...
    sum([report.rows.finalValidationPass]),sum([report.rows.plannerTimedOut]));
end

function out=mergeLocal(defaults,in)
out=defaults;
names=fieldnames(defaults);
for i=1:numel(names)
    if isfield(in,names{i}) && ~isempty(in.(names{i}))
        out.(names{i})=in.(names{i});
    end
end
end
