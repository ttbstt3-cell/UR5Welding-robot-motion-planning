function report = test_accp_adaptive_time_scaling_integration(inputFile, outputFile)
%TEST_ACCP_ADAPTIVE_TIME_SCALING_INTEGRATION
% Validate ACCP Stage 3 against the frozen 31-node Cartesian-refined path.
% This is an offline regression only; it never publishes or executes motion.
if nargin < 1 || isempty(inputFile)
    inputFile = fullfile(fileparts(fileparts(mfilename('fullpath'))), ...
        'planning_runs','accp_embedded_precision_20261012','embedded_accp.mat');
end
if nargin < 2 || isempty(outputFile)
    outputFile = fullfile(fileparts(fileparts(mfilename('fullpath'))), ...
        'planning_runs','accp_embedded_precision_20261012', ...
        'adaptive_time_scaling_integration_report.json');
end
S = load(inputFile,'result');
assert(isfield(S,'result'),'Input must contain result.');
r = S.result;
assert(isfield(r,'qPath') && size(r.qPath,2)==6 && size(r.qPath,1)==31, ...
    'ACCP Stage 3 must preserve exactly 31 q nodes.');
assert(isfield(r,'tcpPosePath') && numel(r.tcpPosePath)==31, ...
    '31 TCP target poses are required.');
assert(isfield(r,'scene') && isfield(r.scene,'robot'), ...
    'The validated ACCP scene is required.');

collisionPass = logical(localGet(r,'nodeCollisionFree',false)) && ...
    logical(localGet(r,'edgeCollisionFree',false));
t = adaptive_time_scale_accp_output(r.qPath,r.tcpPosePath,r.scene,struct( ...
    'maxVelocityRadPerSec',localGet(r.options,'timeScalingMaxVelocityRadPerSec',deg2rad(5)), ...
    'maxAccelerationRadPerSec2',localGet(r.options,'timeScalingMaxAccelerationRadPerSec2',deg2rad(15)), ...
    'maxDurationSec',localGet(r.options,'timeScalingMaxDurationSec',50), ...
    'lambda',localGet(r.options,'timeScalingLambda',0.001), ...
    'collisionPass',collisionPass, ...
    'collisionSampleCount',localGet(r,'adaptiveCollisionChecks',0)));

assert(t.q_node_count==31 && numel(t.timeFromStart)==31);
assert(size(t.velocities,1)==31 && size(t.velocities,2)==6);
assert(size(t.accelerations,1)==31 && size(t.accelerations,2)==6);
assert(t.tcpContourMaxMm < 0.5,'TCP contour gate failed.');
assert(t.timeSyncMaxMm < 0.5,'TCP time-sync gate failed.');
assert(t.collisionPass && t.jointLimitsPass,'Collision/joint-limit gate failed.');
assert(t.maxSegmentVelocityRadPerSec <= t.velocityLimitRadPerSec + 1e-10);
assert(t.maxSegmentAccelerationRadPerSec2 <= t.accelerationLimitRadPerSec2 + 1e-10);
assert(t.complete && t.executionReady,'ACCP timed output is not execution-ready.');

report = struct('schema_version','ACCP_STAGE3_INTEGRATION_TEST_v1', ...
    'algorithm','ACCP','stages',{{'Continuous IK','Cartesian Refinement','Adaptive Time Scaling'}}, ...
    'robot_motion','NO','input_file',inputFile,'q_node_count',t.q_node_count, ...
    'duration_sec',t.durationSec,'max_velocity_rad_per_sec',t.maxVelocityRadPerSec, ...
    'max_acceleration_rad_per_sec2',t.maxAccelerationRadPerSec2, ...
    'finite_difference_max_acceleration_rad_per_sec2',t.finiteDifferenceMaxAccelerationRadPerSec2, ...
    'tcp_contour_max_mm',t.tcpContourMaxMm,'tcp_contour_rms_mm',t.tcpContourRmsMm, ...
    'time_sync_max_mm',t.timeSyncMaxMm,'time_sync_rms_mm',t.timeSyncRmsMm, ...
    'max_orientation_error_deg',t.maxOrientationErrorDeg, ...
    'collision_pass',t.collisionPass,'collision_sample_count',t.collisionSampleCount, ...
    'joint_limits_pass',t.jointLimitsPass,'execution_ready',t.executionReady, ...
    'collision_validation_source',t.collisionValidationSource);
localEnsureParent(outputFile);
fid=fopen(outputFile,'w'); assert(fid>=0,'Cannot write %s',outputFile);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(report,'PrettyPrint',true));
fprintf('ACCP Stage 3 integration regression: PASS (31 nodes, NO ROBOT MOTION)\n');
disp(report);
end

function v=localGet(s,name,d)
if isstruct(s) && isfield(s,name), v=s.(name); else, v=d; end
end

function localEnsureParent(p)
d=fileparts(p); if ~isempty(d) && ~isfolder(d), mkdir(d); end
end
