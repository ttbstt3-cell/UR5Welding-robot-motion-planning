function report=run_full_welding_execution_validation_current()
%RUN_FULL_WELDING_EXECUTION_VALIDATION_CURRENT Audit current saved evidence.
% This intentionally refuses to borrow old/unbound approach or exit paths.
% It emits a diagnostic JSON report only; it never creates a robot command.
root=fileparts(fileparts(mfilename('fullpath')));
out=fullfile(root,'规划文件','real_anchor_runs','full_welding_execution_validation_20261014');
if ~isfolder(out), mkdir(out); end
dataDir=fullfile(root,'规划文件','real_anchor_runs','hybrid_velocity_20261014_final');
hybridMat=fullfile(dataDir,'hybrid_velocity_diagnostic.mat');
hybridJson=fullfile(dataDir,'report.json');
sceneMat=fullfile(root,'规划文件','real_anchor_runs','accp_bridge_comparison_20261013_improved_full_cold_v2.mat');
assert(isfile(hybridMat) && isfile(hybridJson) && isfile(sceneMat),...
    'Current ACCP-D or its offline scene evidence is missing.');
load(hybridMat,'r'); hReport=localReadJson(hybridJson);
load(sceneMat,'result'); scene=result.scene;
assert(isequal(r.calibrationBinding,scene.calibrationBinding),...
    'ACCP-D and saved scene calibration bindings differ; do not validate a mixed scene.');
assert(isequal(r.calibrationBinding,hReport.calibrationBinding),...
    'ACCP-D MAT and JSON report bindings differ; reject mixed evidence.');

% The latest successful approach is an old, unbound path. The newest REAL
% attempt failed before producing a trajectory. The only exit path is old
% and unbound. Keep both absent here so the validator cannot silently splice.
approach=struct('available',false,'reason','No current version-bound REAL approach path.');
exit=struct('available',false,'reason','No current version-bound REAL exit path.');
weld=struct('qPath',r.qPath,'tcpPosePath',{r.tcpPosePath},...
    'timeFromStart',r.timeFromStart,'velocities',r.velocities{4},...
    'binding',r.calibrationBinding,'name','ACCP-D');
report=validate_full_welding_execution(approach,weld,exit,scene,...
    r.calibrationBinding,struct('minControllerSamples',5000,...
    'maxTcpContourErrorMm',0.5,'maxTcpTimeSyncErrorMm',0.5,...
    'maxTcpOrientationErrorDeg',0.5,'maxVelocityRadPerSec',deg2rad(5),...
    'maxAccelerationRadPerSec2',0.261799,'tcpBodyName','WeldTCP'));

oldApproach=localReadJson(fullfile(root,'规划文件',...
    'online_realhome_to_preweld_v1_fastconnect_anytime_rrt_star_hmi_20261010_105205_168803_report.json'));
latestApproach=localReadJson(fullfile(root,'规划文件',...
    'online_realhome_to_preweld_v1_fastconnect_anytime_rrt_star_hmi_20261012_102457_109585_report.json'));
oldExit=localReadJson(fullfile(root,'规划文件',...
    'online_postweld_to_realhome_v1_fastconnect_anytime_rrt_star_hmi_20261008_172136_837652_report.json'));
oldFull=localReadJson(fullfile(root,'规划文件',...
    'online_full_welding_task_v1_fastconnect_anytime_rrt_star_hmi_20261008_171916_720017_report.json'));

report.created_at=char(datetime('now','Format','yyyy-MM-dd''T''HH:mm:ss'));
report.task='RealHome -> CBi-RRT* approach -> PreWeld -> ACCP-D -> PostWeld -> CBi-RRT* exit -> RealHome';
report.current_weld_segment=struct('source_mat',hybridMat,'source_report',hybridJson,...
    'strategy','D_HYBRID','node_count',size(r.qPath,1),'duration_sec',r.timeFromStart(end),...
    'controller_interpolation',r.audits{4},'derivative_metrics',r.derivativeMetrics{4},...
    'wire_collision_shorten_mm',r.wireCollisionShortenMm,...
    'collision_sampling_is_not_a_continuous_proof',~r.continuousCollisionProof);
report.legacy_evidence=struct();
report.legacy_evidence.approach=struct('report','UR5/规划文件/online_realhome_to_preweld_v1_fastconnect_anytime_rrt_star_hmi_20261010_105205_168803_report.json',...
    'success',oldApproach.success,'binding','MISSING_STALE',...
    'diagnostic_only_q_end_rad',oldApproach.q_end_rad,...
    'delta_to_current_accp_start_rad',oldApproach.q_end_rad-r.qPath(1,:),...
    'max_abs_joint_delta_rad',max(abs(oldApproach.q_end_rad-r.qPath(1,:))),...
    'norm_joint_delta_rad',norm(oldApproach.q_end_rad-r.qPath(1,:)));
report.legacy_evidence.latest_real_approach=struct('report','UR5/规划文件/online_realhome_to_preweld_v1_fastconnect_anytime_rrt_star_hmi_20261012_102457_109585_report.json',...
    'success',latestApproach.success,'failure_reason',latestApproach.failure_reason,...
    'output_path',localField(latestApproach,'output_file',[]),'status','FAILED_NO_PATH');
report.legacy_evidence.exit=struct('report','UR5/规划文件/online_postweld_to_realhome_v1_fastconnect_anytime_rrt_star_hmi_20261008_172136_837652_report.json',...
    'success',oldExit.success,'binding','MISSING_STALE',...
    'diagnostic_only_q_start_rad',oldExit.q_start_rad,...
    'delta_from_current_accp_end_rad',r.qPath(end,:)-oldExit.q_start_rad,...
    'max_abs_joint_delta_rad',max(abs(r.qPath(end,:)-oldExit.q_start_rad)),...
    'norm_joint_delta_rad',norm(r.qPath(end,:)-oldExit.q_start_rad));
report.legacy_evidence.full_task=struct('report','UR5/规划文件/online_full_welding_task_v1_fastconnect_anytime_rrt_star_hmi_20261008_171916_720017_report.json',...
    'success',oldFull.success,'binding','MISSING_STALE','point_count',oldFull.point_count,...
    'duration_sec',oldFull.duration_sec,'collision_sample_count',oldFull.dense_validation.collision_configuration_checks,...
    'usable_for_current_validation',false);
report.full_trajectory_was_stitched=false;
report.full_controller_sample_count=0;
report.full_controller_validation='NOT_RUN_MISSING_CURRENT_APPROACH_AND_EXIT';
report.executionReady=false;
report.validation_status='BLOCKED';
report.no_motion_statement='No robot motion, no FollowJointTrajectory goal, and no executable trajectory was generated.';
jsonPath=fullfile(out,'full_welding_execution_validation.json');
report.output_json=jsonPath;
fid=fopen(jsonPath,'w'); assert(fid>=0,'Cannot write validation JSON.');
cleanup=onCleanup(@()fclose(fid)); fwrite(fid,jsonencode(report,'PrettyPrint',true),'char'); clear cleanup;
fprintf('FULL_WELDING_VALIDATION_BLOCKED missing current version-bound approach/exit. JSON: %s\n',jsonPath);
end

function x=localReadJson(path)
assert(isfile(path),'Expected evidence file is missing: %s',path);
fid=fopen(path,'r'); assert(fid>=0,'Cannot open evidence file: %s',path);
c=onCleanup(@()fclose(fid)); x=jsondecode(fread(fid,Inf,'*char').'); clear c;
end
function x=localField(s,k,d), if isfield(s,k), x=s.(k); else, x=d; end, end
