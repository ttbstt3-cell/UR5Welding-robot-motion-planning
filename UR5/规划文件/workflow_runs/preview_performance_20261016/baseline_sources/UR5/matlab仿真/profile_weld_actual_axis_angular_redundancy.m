function report = profile_weld_actual_axis_angular_redundancy()
%PROFILE_WELD_ACTUAL_AXIS_ANGULAR_REDUNDANCY
% Conditional Gao-style angular-redundancy recovery experiment.
% The fast 5->9 progressive continuation remains the main path; only a
% failed layer tries +/-10 and +/-20 degree redundant tool-angle offsets.

here = fileparts(mfilename("fullpath"));
opts = struct( ...
    "animate",false,"publish",false,"enableFallback",false, ...
    "beamWidth",1,"firstPointMaxStates",2,"maxPoseSeeds",3, ...
    "maxPoseNeighbors",9,"numRandomSeedsFirstPoint",3, ...
    "coarseTravelDeg",0,"coarseRollDeg",0:45:315, ...
    "progressivePoseNeighbors",true, ...
    "progressiveInitialPoseNeighbors",5, ...
    "progressiveMaxPoseNeighbors",9, ...
    "angularRedundancyFallback",true, ...
    "angularFallbackRollDeg",[10 20], ...
    "angularFallbackTravelDeg",[0 5 10], ...
    "outputFile","weld_actual_axis_replan_angular_redundancy.mat");

t=tic;
result=replan_weld_actual_axis_continuation(opts);
wallTimeSec=toc(t);
report=struct("created",char(datetime("now","Format","yyyy-MM-dd HH:mm:ss")), ...
    "options",opts,"wallTimeSec",wallTimeSec, ...
    "algorithmTimeSec",result.algorithmElapsedSec, ...
    "ikElapsedSec",result.continuationStats.ikElapsedSec, ...
    "ikCalls",result.continuationStats.ikCalls,"result",result);
save(fullfile(here,"weld_actual_axis_angular_redundancy_profile.mat"), ...
    "report","-v7.3");

fprintf("\nAngular-redundancy profile complete.\n");
fprintf("Algorithm time  : %.3f s\n",result.algorithmElapsedSec);
fprintf("Wall time       : %.3f s\n",wallTimeSec);
fprintf("IK time         : %.3f s\n",result.continuationStats.ikElapsedSec);
fprintf("IK calls        : %d\n",result.continuationStats.ikCalls);
fprintf("PASS             : %d\n",result.complete);
fprintf("Saved result     : %s\n",fullfile(here,opts.outputFile));
end
