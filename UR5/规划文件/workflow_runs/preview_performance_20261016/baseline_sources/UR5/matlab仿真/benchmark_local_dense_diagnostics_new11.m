function report=benchmark_local_dense_diagnostics_new11()
%BENCHMARK_LOCAL_DENSE_DIAGNOSTICS_NEW11
% Batch diagnostic for the 11 failures from the independent new100 set.
% This calls the existing local dense analyzer only; it does not modify the
% A-ARC-IK planner or its parameters.

root=fileparts(mfilename('fullpath'));
seeds=[20270003 20270004 20270007 20270054 20270057 20270062 ...
    20270071 20270078 20270085 20270092 20270095];
files=string(fullfile(root,'adaptive_arc_ik_new100_runs', ...
    "adaptive_new100_seed"+string(seeds)+".mat"));
outDir=fullfile(root,'local_dense_connectivity_new11_runs');
opts=struct( ...
    'failureFiles',files, ...
    'windowHalfWidth',2, ...
    'intervalSubdivisions',4, ...
    'offsetGrid',-30:5:30, ...
    'maxSeedsPerPose',16, ...
    'randomSeedsPerPose',6, ...
    'maxStatesPerLayer',1000, ...
    'maxRollStepDeg',15, ...
    'maxTravelStepDeg',5, ...
    'maxJointStepDeg',15, ...
    'edgeResolutionDeg',3, ...
    'outputDir',outDir, ...
    'outputMat',fullfile(root,'local_dense_connectivity_new11.mat'), ...
    'outputCsv',fullfile(root,'local_dense_connectivity_new11.csv'), ...
    'randomSeedBase',99200);
report=analyze_local_dense_connectivity(opts);
end
