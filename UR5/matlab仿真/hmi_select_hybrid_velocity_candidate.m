function [V,selection]=hmi_select_hybrid_velocity_candidate(hybrid,base,scene)
% Candidate handoff only. Does NOT certify task joins, environment or servo.
% Never use an unfinished solver iterate or an unverified C fallback.
assert(isequal(hybrid.qPath,base.qPath) &&...
    isequal(hybrid.tcpPosePath,base.tcpPosePath) &&...
    isequal(hybrid.timeFromStart,base.timeFromStart(:)),...
    'PREPARE:HybridContract','Hybrid changed immutable q/TCP/time input');
assert(isequal(hybrid.calibrationBinding,base.calibrationBinding),...
    'PREPARE:HybridContract','Hybrid calibration binding mismatch');
assert(isequal(hybrid.executionReady,false) && isequal(hybrid.offlineOnly,true),...
    'PREPARE:HybridContract','Hybrid candidate must not grant execution permission');
assert(islogical(hybrid.hybridCandidateFound) && isscalar(hybrid.hybridCandidateFound),...
    'PREPARE:HybridContract','Invalid Hybrid result flag');
if hybrid.hybridCandidateFound
    V=hybrid.velocities{4}; audit=hybrid.audits{4}; source='D_HYBRID';
else
    assert(isequal(base.audits{4}.complete,true),...
        'PREPARE:HybridCandidateInvalid','C seed failed its original weld audit');
    V=base.velocities{4}; audit=hybrid.audits{3}; source='C_ACCURACY_FALLBACK';
    assert(isequal(V,hybrid.velocities{3}) && isequal(V,hybrid.velocities{4}),...
        'PREPARE:HybridContract','Fallback must be the exact audited C, not a stopped QP iterate');
end
assert(isequal(size(V),size(base.qPath)) && all(isfinite(V(:))),...
    'PREPARE:HybridCandidateInvalid','Candidate velocity data invalid');
for f={'complete','collision_pass','joint_limits_pass','analytic_derivative_and_position_extrema_pass'}
    assert(isfield(audit,f{1}) && isequal(audit.(f{1}),true),...
        'PREPARE:HybridCandidateInvalid','Candidate weld audit failed or missing: %s',f{1});
end
assert(strcmp(audit.interpolation_mode,'positions_plus_velocities_cubic_hermite') &&...
    audit.sample_count>=3001,'PREPARE:HybridCandidateInvalid','Incomplete candidate interpolation audit');
for f={'max_tcp_contour_error_mm','max_tcp_time_sync_error_mm','max_tcp_orientation_error_deg'}
    v=audit.(f{1});
    assert(isnumeric(v) && isscalar(v) && isfinite(v) && v>=0 && v<=0.5,...
        'PREPARE:HybridCandidateInvalid','Candidate precision failed: %s',f{1});
end
% Re-evaluate analytic extrema against THIS request's unchanged limits.
limits=hmi_scene_motion_limits(scene); m=accp_cubic_derivative_metrics(base.qPath,base.timeFromStart,V);
assert(m.max_velocity<=limits.velocityLimit && m.max_acceleration<=limits.accelerationLimit &&...
    all(m.position_min>=scene.jointLimits(:,1).') && all(m.position_max<=scene.jointLimits(:,2).'),...
    'PREPARE:HybridCandidateInvalid','Candidate analytic extrema/limits failed');
selection=struct('source',source,'nonoptimal_fallback',~hybrid.hybridCandidateFound,...
    'scope','WELD_SEGMENT_ONLY','candidate_accepted',true,'executionReady',false,...
    'requires_global_continuity',true,'requires_full_task_validation',true,...
    'q_tcp_time_unchanged',true,'weld_audit_pass',true,...
    'note','Candidate recovery is not task validation or physical execution permission');
end
