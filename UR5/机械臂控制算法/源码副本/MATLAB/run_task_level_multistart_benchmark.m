function summary = run_task_level_multistart_benchmark(options)
%RUN_TASK_LEVEL_MULTISTART_BENCHMARK
% Task-level first-feasible experiment.  A random seed is an initialization
% only; a Seam task stops at the first complete valid trajectory.
%
% This wrapper does not change A-ARC-IK+ or the Forward/Reverse cascade.
% It runs a small, independent validation set with up to five restarts and
% a 60 s end-to-end task budget.

if nargin < 1 || isempty(options), options = struct(); end
root = fileparts(mfilename('fullpath'));
defaults = struct( ...
    'seeds',20270801:20270810, ...
    'maxAttempts',5, ...
    'timeBudgetSec',60, ...
    'outputDir',fullfile(root,'task_level_multistart_runs'), ...
    'csvFile',fullfile(root,'task_level_multistart.csv'), ...
    'attemptCsvFile',fullfile(root,'task_level_multistart_attempts.csv'), ...
    'matFile',fullfile(root,'task_level_multistart.mat'), ...
    'resume',true);
f = fieldnames(options);
for k = 1:numel(f), defaults.(f{k}) = options.(f{k}); end

summary = benchmark_multistart_first_feasible(defaults);
summary.evaluationDefinition = [ ...
    "Task-level feasibility: a Seam task is PASS when any restart finds one " ...
    "complete node/edge/TCP/collision-valid trajectory within the total budget."];
summary.maxAttempts = defaults.maxAttempts;
summary.timeBudgetSec = defaults.timeBudgetSec;
save(defaults.matFile,'summary','-v7.3');
end
