function summary=summarize_fixed_support_cold_run(runDir,outFile)
% Read-only summary: distinguish generated paths from safe/executable paths.
raw=load(fullfile(runDir,'full_raw_trajectory.mat'));
s=load(raw.sceneFile,'scene'); scene=s.scene;
w=load(fullfile(runDir,'preview_accp.mat'),'result'); weld=w.result;
a=load(fullfile(runDir,'approach_planner.mat'),'p'); e=load(fullfile(runDir,'exit_planner.mat'),'p');
audit=jsondecode(fileread(fullfile(runDir,'preview_display_audit.json')));
summary=struct('robot_motion','NO','executionReady',false,'run_directory',runDir,...
    'cold_start',true,'source','Actual HMI request, no old qPath or state-bank reuse',...
    'calibration_binding',raw.metadata.calibration_binding,...
    'fixed_contact',scene.fixedEnvironmentContact,...
    'preview_node_count',size(raw.qPath,1),'preview_duration_s',raw.timeFromStart(end),...
    'preview_collision_status',audit.collision_status,'preview_sample_count',audit.collision_sample_count,...
    'preview_collision_hit_samples',audit.collision_hit_count,'collision_pairs',{audit.collision_pairs},...
    'first_collision_frame',audit.first_collision_frame,'first_collision_sample',audit.first_collision_sample,...
    'previewReady',audit.previewReady);
summary.approach=planner(a.p,scene.jointLimits);
summary.exit=planner(e.p,scene.jointLimits);
summary.accp=struct('configuration_complete',weld.configurationComplete,...
    'cartesian_refinement_complete',weld.adaptiveCorrectionComplete,...
    'timing_complete',weld.timeParameterizationComplete,'complete',weld.complete,...
    'initial_nodes',size(weld.qPathInitial,1),'refined_nodes',size(weld.qPath,1),...
    'ik_calls',weld.continuationStats.ikCalls,...
    'configuration_time_s',weld.configurationSearchTimeSec,...
    'total_time_s',weld.totalPlanningTimeSec,...
    'node_collision_free',weld.nodeCollisionFree,'edge_collision_free',weld.edgeCollisionFree,...
    'maximum_cartesian_error_mm',max(weld.cartesianRefinement.finalTcpMetrics.segmentPositionErrorMm),...
    'bridge_recovered_points',weld.cartesianBridge.recovered_point_indices,...
    'time_failure_reason',weld.timeParameterizationFailureReason);
cv=weld.timeParameterization.controllerInterpolationValidation;
summary.accp.controller_validation=struct();
for name=fieldnames(cv).'
    value=cv.(name{1});
    if (isnumeric(value)||islogical(value)) && isscalar(value) || ischar(value) || isstring(value)
        summary.accp.controller_validation.(name{1})=value;
    end
end
summary.floor_collision_pair_count=0;
for k=1:numel(audit.collision_pair_summary)
    pair=audit.collision_pair_summary(k);
    if contains(pair.pair,'EnvironmentCollision_Floor')
        summary.floor_collision_pair_count=summary.floor_collision_pair_count+pair.occurrence_count;
    end
end
summary.floor_scope='All original moving robot/gun/wire pairs checked; only certified fixed base/Floor masked';
Q=raw.qPath; L=scene.jointLimits;
violations=Q<L(:,1).'-1e-10 | Q>L(:,2).'+1e-10;
summary.preview_joint_limits_pass=~any(violations(:));
[ii,jj]=find(violations); summary.preview_joint_limit_violations=struct('frame',{},'joint',{},'q_deg',{});
for k=1:numel(ii)
    summary.preview_joint_limit_violations(k)=struct('frame',ii(k),'joint',jj(k),'q_deg',rad2deg(Q(ii(k),jj(k))));
end
summary.segment_counts=struct(); summary.boundaries=cell(1,numel(raw.segments)-1);
for k=1:numel(raw.segments)
    seg=raw.segments{k}; summary.segment_counts.(seg.label)=size(seg.qPath,1);
    if k==numel(raw.segments), continue; end
    next=raw.segments{k+1}; qa=seg.qPath(end,:); qb=next.qPath(1,:);
    Ta=getTransform(scene.robot,qa,scene.tcpBodyName); Tb=getTransform(scene.robot,qb,scene.tcpBodyName);
    angle=acos(max(-1,min(1,(trace(Ta(1:3,1:3)'*Tb(1:3,1:3))-1)/2)));
    summary.boundaries{k}=struct('from',seg.label,'to',next.label,...
        'delta_q_deg',rad2deg(qb-qa),...
        'wrapped_delta_q_deg',rad2deg(atan2(sin(qb-qa),cos(qb-qa))),...
        'TCP_position_difference_mm',1000*norm(Ta(1:3,4)-Tb(1:3,4)),...
        'TCP_rotation_difference_deg',rad2deg(angle));
end
summary.note='Ground goal passes sampled preview only. Workpiece junction collision and timing/representation failures remain BLOCKED; no auto-fix.';
fid=fopen(outFile,'w'); assert(fid>=0); c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(summary,'PrettyPrint',true),'char');
end
function value=planner(p,limits)
value=struct('success',p.success,'termination_reason',p.terminationReason,...
    'planning_time_s',p.planningTime,'path_nodes',size(p.path,1),...
    'stage1_iterations',p.stage1Iterations,'stage2_iterations',p.stage2Iterations,...
    'collision_state_checks',p.collisionConfigurationChecks,'edge_checks',p.edgeCollisionChecks,...
    'source_nodes_joint_limits_pass',all(p.path>=limits(:,1).'-1e-10 & p.path<=limits(:,2).'+1e-10,'all'));
end
