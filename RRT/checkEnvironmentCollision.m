function [hit,distance,witness,contact]=checkEnvironmentCollision(robot,q,worldObjects,policy)
% Environment collision adapter. No geometry/threshold/search changes.
% A certified fixed support is masked by ONE body/environment matrix cell.
% Every other native exhaustive pair remains exactly as returned by MATLAB.
if nargin<4, policy=[]; end
[raw,distance,witness]=checkCollision(robot,q,worldObjects,...
    'IgnoreSelfCollision','on','Exhaustive','on');
hit=raw;
contact=struct('status','NONE','pair',{{}},'raw_contact',false,'raw_environment_collision',any(raw(:)));
if isempty(policy), return; end
assert(isstruct(policy) && isscalar(policy) && ...
    strcmp(policy.status,'MODEL_VERIFIED_FIXED_SUPPORT') && ...
    isequal(policy.pair,{'base_link_inertia','EnvironmentCollision_Floor'}),...
    'FIXED_SUPPORT:Policy','Unsupported environment exception');
i=policy.body_index; j=policy.environment_index;
assert(i<=numel(robot.BodyNames) && strcmp(robot.BodyNames{i},policy.pair{1}) && ...
    j<=numel(worldObjects) && isequal(worldObjects{j}.Pose,policy.floor_pose) && ...
    isa(worldObjects{j},'collisionBox') && ...
    isequal([worldObjects{j}.X worldObjects{j}.Y worldObjects{j}.Z],policy.floor_size_m),...
    'FIXED_SUPPORT:STALE','Certified body/floor identity or geometry changed');
assert(isequal(getTransform(robot,q,policy.pair{1}),policy.T_root_base_body),...
    'FIXED_SUPPORT:STALE','Certified base is no longer at its fixed installation pose');
assert(size(distance,1)==numel(robot.BodyNames)+1 && size(distance,2)==numel(worldObjects) && ...
    any(raw(:))==any(isnan(distance(:))),...
    'FIXED_SUPPORT:NativeMatrix','Native exhaustive flag/distance matrix is inconsistent; refusing exception');
contact.status='EXEMPT_FIXED_INSTALLATION_CONTACT'; contact.pair=policy.pair;
contact.raw_contact=isnan(distance(i,j));
distance(i,j)=Inf; % Not zero clearance: the exempt pair is excluded from min-gap statistics.
hit=any(isnan(distance(:)));
end
