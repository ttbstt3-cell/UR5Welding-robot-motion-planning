function [comparison,combined] = compare_v1_taskA_taskB(options)
%compare_v1_taskA_taskB Combine the two frozen Seam-A free-space tasks.
%
% The RRT comparison contains only qHome -> qPreWeld and
% qPostWeld -> qHome.  The deterministic local links to/from Point 1 and
% Point 80 remain outside this table, as required by the welding workflow.

if nargin < 1 || isempty(options), options=struct(); end
root=fileparts(fileparts(mfilename('fullpath')));
defaults=struct( ...
    'taskAFile',fullfile(root,'results','v1_fast_connect_anytime_taskA_seed20260917.mat'), ...
    'taskBFile',fullfile(root,'results','v1_fast_connect_anytime_taskB_seed20260917.mat'), ...
    'comparisonCsv',fullfile(root,'results','v1_seamA_taskA_taskB_comparison.csv'), ...
    'combinedCsv',fullfile(root,'results','v1_seamA_taskA_taskB_combined.csv'), ...
    'outputMat',fullfile(root,'results','v1_seamA_taskA_taskB_combined.mat'));
names=fieldnames(options);
for i=1:numel(names), defaults.(names{i})=options.(names{i}); end
options=defaults;

a=load(options.taskAFile,'report'); taskA=a.report;
b=load(options.taskBFile,'report'); taskB=b.report;
if numel(taskA.rows)~=numel(taskB.rows)
    error('Task A and Task B algorithm row counts differ.');
end

n=numel(taskA.rows);
comparison=table(strings(n*2,1),strings(n*2,1),strings(n*2,1), ...
    NaN(n*2,1),NaN(n*2,1),NaN(n*2,1),NaN(n*2,1),NaN(n*2,1), ...
    NaN(n*2,1),false(n*2,1),false(n*2,1), ...
    'VariableNames',{'algorithm','task','taskDescription', ...
    'firstSolutionTimeSec','firstPathLengthL2Rad','bestPathLengthAt10s', ...
    'bestPathLengthAt30s','planningTimeSec','totalJointMotionRad', ...
    'validSuccess','denseValidationPass'});

for i=1:n
    k=2*i-1;
    comparison.algorithm(k)=string(taskA.rows(i).algorithm);
    comparison.task(k)="Task A";
    comparison.taskDescription(k)=string(taskA.rows(i).description);
    comparison.firstSolutionTimeSec(k)=taskA.rows(i).firstSolutionTimeSec;
    comparison.firstPathLengthL2Rad(k)=taskA.rows(i).firstPathLengthL2Rad;
    comparison.bestPathLengthAt10s(k)=taskA.rows(i).bestPathLengthAt10s;
    comparison.bestPathLengthAt30s(k)=taskA.rows(i).bestPathLengthAt30s;
    comparison.planningTimeSec(k)=taskA.rows(i).planningTimeSec;
    comparison.totalJointMotionRad(k)=taskA.rows(i).totalJointMotionRad;
    comparison.validSuccess(k)=taskA.rows(i).validSuccess;
    comparison.denseValidationPass(k)=taskA.rows(i).finalDenseValidationPass;

    comparison.algorithm(k+1)=string(taskB.rows(i).algorithm);
    comparison.task(k+1)="Task B";
    comparison.taskDescription(k+1)=string(taskB.rows(i).description);
    comparison.firstSolutionTimeSec(k+1)=taskB.rows(i).firstSolutionTimeSec;
    comparison.firstPathLengthL2Rad(k+1)=taskB.rows(i).firstPathLengthL2Rad;
    comparison.bestPathLengthAt10s(k+1)=taskB.rows(i).bestPathLengthAt10s;
    comparison.bestPathLengthAt30s(k+1)=taskB.rows(i).bestPathLengthAt30s;
    comparison.planningTimeSec(k+1)=taskB.rows(i).planningTimeSec;
    comparison.totalJointMotionRad(k+1)=taskB.rows(i).totalJointMotionRad;
    comparison.validSuccess(k+1)=taskB.rows(i).validSuccess;
    comparison.denseValidationPass(k+1)=taskB.rows(i).finalDenseValidationPass;
end

combined=table(strings(n,1), ...
    NaN(n,1),NaN(n,1),NaN(n,1), ...
    NaN(n,1),NaN(n,1),NaN(n,1), ...
    NaN(n,1),NaN(n,1),NaN(n,1), ...
    NaN(n,1),NaN(n,1),NaN(n,1), ...
    NaN(n,1),NaN(n,1),NaN(n,1), ...
    false(n,1),false(n,1),false(n,1), ...
    'VariableNames',{'algorithm', ...
    'approachFirstTimeSec','exitFirstTimeSec','totalFirstTimeSec', ...
    'approachFirstPathLengthL2Rad','exitFirstPathLengthL2Rad', ...
    'totalFirstPathLengthL2Rad', ...
    'approachBestPathLengthAt10s','exitBestPathLengthAt10s', ...
    'totalBestPathLengthAt10s', ...
    'approachBestPathLengthAt30s','exitBestPathLengthAt30s', ...
    'totalBestPathLengthAt30s', ...
    'approachPlanningTimeSec','exitPlanningTimeSec', ...
    'totalPlanningTimeSec','approachValidSuccess','exitValidSuccess', ...
    'bothValidSuccess'});

for i=1:n
    combined.algorithm(i)=string(taskA.rows(i).algorithm);
    combined.approachFirstTimeSec(i)=taskA.rows(i).firstSolutionTimeSec;
    combined.exitFirstTimeSec(i)=taskB.rows(i).firstSolutionTimeSec;
    combined.totalFirstTimeSec(i)=sum([combined.approachFirstTimeSec(i), ...
        combined.exitFirstTimeSec(i)],'omitnan');
    combined.approachFirstPathLengthL2Rad(i)=taskA.rows(i).firstPathLengthL2Rad;
    combined.exitFirstPathLengthL2Rad(i)=taskB.rows(i).firstPathLengthL2Rad;
    combined.totalFirstPathLengthL2Rad(i)=sum([ ...
        combined.approachFirstPathLengthL2Rad(i), ...
        combined.exitFirstPathLengthL2Rad(i)],'omitnan');
    combined.approachBestPathLengthAt10s(i)=taskA.rows(i).bestPathLengthAt10s;
    combined.exitBestPathLengthAt10s(i)=taskB.rows(i).bestPathLengthAt10s;
    combined.totalBestPathLengthAt10s(i)=sum([ ...
        combined.approachBestPathLengthAt10s(i), ...
        combined.exitBestPathLengthAt10s(i)],'omitnan');
    combined.approachBestPathLengthAt30s(i)=taskA.rows(i).bestPathLengthAt30s;
    combined.exitBestPathLengthAt30s(i)=taskB.rows(i).bestPathLengthAt30s;
    combined.totalBestPathLengthAt30s(i)=sum([ ...
        combined.approachBestPathLengthAt30s(i), ...
        combined.exitBestPathLengthAt30s(i)],'omitnan');
    combined.approachPlanningTimeSec(i)=taskA.rows(i).planningTimeSec;
    combined.exitPlanningTimeSec(i)=taskB.rows(i).planningTimeSec;
    combined.totalPlanningTimeSec(i)=sum([ ...
        combined.approachPlanningTimeSec(i), ...
        combined.exitPlanningTimeSec(i)],'omitnan');
    combined.approachValidSuccess(i)=taskA.rows(i).validSuccess;
    combined.exitValidSuccess(i)=taskB.rows(i).validSuccess;
    combined.bothValidSuccess(i)=combined.approachValidSuccess(i) && ...
        combined.exitValidSuccess(i);
end

writetable(comparison,options.comparisonCsv);
writetable(combined,options.combinedCsv);
save(options.outputMat,'comparison','combined','taskA','taskB','-v7.3');

fprintf('\nCBi-RRT* SEAM A TASK A/B COMPARISON\n');
disp(comparison(:,{'algorithm','task','firstSolutionTimeSec', ...
    'firstPathLengthL2Rad','bestPathLengthAt10s','bestPathLengthAt30s', ...
    'validSuccess','denseValidationPass'}));
fprintf('Combined totals (approach + exit):\n');
disp(combined(:,{'algorithm','totalFirstTimeSec', ...
    'totalFirstPathLengthL2Rad','totalBestPathLengthAt10s', ...
    'totalBestPathLengthAt30s','totalPlanningTimeSec','bothValidSuccess'}));
fprintf('Comparison CSV: %s\n',options.comparisonCsv);
fprintf('Combined CSV:   %s\n',options.combinedCsv);
end
