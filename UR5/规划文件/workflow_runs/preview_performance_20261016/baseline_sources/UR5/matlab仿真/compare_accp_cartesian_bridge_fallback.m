function report = compare_accp_cartesian_bridge_fallback(baselineFile,improvedFile,outputFile)
%COMPARE_ACCP_CARTESIAN_BRIDGE_FALLBACK Offline baseline/improved report.
% This function never changes a planner result, writes a formal executable
% trajectory, or communicates with ROS.
if nargin<1 || isempty(baselineFile), error('baselineFile is required.'); end
if nargin<2 || isempty(improvedFile), error('improvedFile is required.'); end
if nargin<3 || isempty(outputFile)
    outputFile=fullfile(fileparts(improvedFile),'accp_bridge_comparison_report.json');
end
B=load(baselineFile,'result'); I=load(improvedFile,'result');
B=B.result; I=I.result;
base=localRunSummary(B,'baseline_original_accp');
improved=localRunSummary(I,'improved_accp_with_cartesian_bridge');
bridge=localBridgeSummary(I);
timed=localTimedSummary(I);
report=struct();
report.schema_version='ACCP_CARTESIAN_BRIDGE_COMPARISON_v1';
report.created=char(datetime('now','Format','yyyy-MM-dd HH:mm:ss'));
report.robot_motion='NO';
report.formal_execution_ready=false;
report.execution_ready_reason='OFFLINE_DIAGNOSTIC_ONLY: no result from this report may be sent to FollowJointTrajectory';
report.baseline=base; report.improved=improved;
report.cartesian_bridge=bridge; report.controller_timed_validation=timed;
report.comparison=struct(...
    'original_configuration_success_rate',double(base.configuration_complete),...
    'improved_configuration_success_rate',double(improved.configuration_complete),...
    'original_failure_point',base.failure_point_index,...
    'improved_recovery_points',bridge.recovered_point_indices,...
    'improved_added_selected_bridge_nodes',bridge.selected_path_added_nodes,...
    'improved_total_expanded_nodes',improved.expanded_seam_point_count-base.original_seam_point_count,...
    'improved_total_ik_calls',improved.total_ik_calls,...
    'improved_configuration_planning_time_sec',improved.configuration_search_time_sec,...
    'improved_total_planning_time_sec',improved.total_planning_time_sec,...
    'improved_full_weld_configuration_pass',improved.full_weld_configuration_pass,...
    'improved_controller_timed_pass',timed.complete,...
    'improved_full_weld_final_pass',logical(improved.full_weld_configuration_pass && timed.complete),...
    'improved_execution_ready',false);
report.safety_notes={...
    'Bridge nodes and edges use the same hard IK, joint-limit, direction and collision gates.',...
    'Every bridge edge uses at least 101 configuration samples; this is dense evidence, not a mathematical continuous-collision proof.',...
    'The accepted bridge path clearance is reported separately from rejected near-miss attempts.',...
    'wire_collision_shorten_mm=3 remains an approximate collision parameter requiring physical safety validation.',...
    'Controller-equivalent positions+velocities cubic interpolation is rechecked; any timing/orientation/peak-acceleration failure keeps the result non-executable.'};
[d,n,~]=fileparts(outputFile); if isempty(d), d=pwd; end
if ~isfolder(d), mkdir(d); end
jsonPath=fullfile(d,[n '.json']);
csvPath=fullfile(d,[n '_table.csv']);
report.artifact_json=jsonPath; report.artifact_csv=csvPath;
fid=fopen(jsonPath,'w'); if fid<0, error('Cannot write %s',jsonPath); end
cleanup=onCleanup(@()fclose(fid)); fwrite(fid,jsonencode(report,'PrettyPrint',true),'char'); clear cleanup;
fc=fopen(csvPath,'w');
if fc>=0
    c=onCleanup(@()fclose(fc));
    fprintf(fc,'algorithm,configuration_pass,overall_pass,execution_ready,original_points,expanded_points,failed_point,recovery_points,added_selected_bridge_nodes,total_ik_calls,planning_time_sec,refined_tcp_contour_max_mm,controller_tcp_contour_max_mm,controller_tcp_time_sync_max_mm,controller_orientation_max_deg,controller_max_velocity_rad_s,controller_max_acceleration_rad_s2,collision_pass,selected_bridge_min_clearance_mm,controller_min_clearance_mm\n');
    fprintf(fc,'baseline_original_accp,%d,%d,%d,%g,%g,%s,%s,%g,%g,%.9f,%s,%s,%s,%s,%s,%s,%d,%s,%s\n',...
        base.configuration_complete,base.overall_complete,0,base.original_seam_point_count,base.expanded_seam_point_count,localText(base.failure_point_index),'',0,base.total_ik_calls,base.total_planning_time_sec,localCsv(base.refined_tcp_contour_max_mm),localCsv(NaN),localCsv(NaN),localCsv(NaN),localCsv(NaN),localCsv(NaN),0,localCsv(NaN),localCsv(NaN));
    fprintf(fc,'improved_accp_with_cartesian_bridge,%d,%d,%d,%g,%g,%s,%s,%g,%g,%.9f,%.9f,%.9f,%.9f,%.9f,%.9f,%.9f,%d,%.9f,%.9f\n',...
        improved.configuration_complete,improved.full_weld_configuration_pass,0,improved.original_seam_point_count,improved.expanded_seam_point_count,'',localText(bridge.recovered_point_indices),bridge.selected_path_added_nodes,improved.total_ik_calls,improved.total_planning_time_sec,improved.refined_tcp_contour_max_mm,timed.max_tcp_contour_error_mm,timed.max_tcp_time_sync_error_mm,timed.max_tcp_orientation_error_deg,timed.max_joint_velocity_rad_per_sec,timed.max_joint_acceleration_rad_per_sec2,timed.collision_pass,bridge.selected_path_min_positive_clearance_mm,timed.min_positive_clearance_mm);
    clear c;
end
fprintf('ACCP bridge comparison report: %s\n',jsonPath);
fprintf('Baseline configuration pass=%d (failed point %s); improved configuration pass=%d; controller-timed pass=%d.\n',...
    base.configuration_complete,localText(base.failure_point_index),improved.configuration_complete,timed.complete);
end

function s=localRunSummary(r,label)
seam=fieldOr(r,'seam',struct('numPoints',NaN));
graph=fieldOr(r,'graph',struct('finalReachableCount',0));
stats=fieldOr(r,'continuationStats',struct('ikCalls',0));
s=struct('label',label,'configuration_complete',logical(fieldOr(r,'configurationComplete',false)),...
    'overall_complete',logical(fieldOr(r,'complete',false)),'execution_ready',false,...
    'original_seam_point_count',double(fieldOr(r,'originalSeamPointCount',NaN)),...
    'expanded_seam_point_count',double(fieldOr(seam,'numPoints',NaN)),...
    'final_reachable_state_count',double(fieldOr(graph,'finalReachableCount',0)),...
    'configuration_search_time_sec',double(fieldOr(r,'configurationSearchTimeSec',NaN)),...
    'precision_time_sec',double(fieldOr(r,'precisionAlgorithmTimeSec',NaN)),...
    'total_planning_time_sec',double(fieldOr(r,'totalPlanningTimeSec',NaN)),...
    'continuation_ik_calls',double(fieldOr(stats,'ikCalls',0)),...
    'bridge_ik_calls',0,'total_ik_calls',0,'failure_point_index',NaN,...
    'max_joint_jump_deg',double(fieldOr(r,'maxJointJumpDeg',NaN)),...
    'refined_tcp_contour_max_mm',double(fieldOr(fieldOr(r,'tcpMetrics',struct('maxSegmentPositionErrorMm',NaN)),'maxSegmentPositionErrorMm',NaN)),...
    'refined_tcp_orientation_max_deg',double(fieldOr(fieldOr(r,'tcpMetrics',struct('maxSegmentOrientationErrorDeg',NaN)),'maxSegmentOrientationErrorDeg',NaN)),...
    'node_collision_free',logical(fieldOr(r,'nodeCollisionFree',false)),...
    'edge_collision_free',logical(fieldOr(r,'edgeCollisionFree',false)),...
    'full_weld_configuration_pass',false);
sb=fieldOr(r,'stateBank',{});
if iscell(sb)
    z=find(cellfun(@isempty,sb),1,'first'); if ~isempty(z), s.failure_point_index=z; end
end
cb=fieldOr(r,'cartesianBridge',struct());
s.bridge_ik_calls=double(fieldOr(cb,'ik_calls',0));
s.total_ik_calls=s.continuation_ik_calls+s.bridge_ik_calls;
s.full_weld_configuration_pass=logical(s.configuration_complete && s.final_reachable_state_count>0 && ...
    all(~cellfun(@isempty,sb)));
if isfield(r,'options') && isfield(r.options,'wire_collision_shorten_mm')
    s.wire_collision_shorten_mm=double(r.options.wire_collision_shorten_mm);
else, s.wire_collision_shorten_mm=NaN; end
end

function b=localBridgeSummary(r)
c=fieldOr(r,'cartesianBridge',struct());
b=struct('enabled',logical(fieldOr(c,'enabled',false)),...
    'recovery_count',double(fieldOr(c,'recovery_count',0)),...
    'recovered_point_indices',fieldOr(c,'recovered_point_indices',zeros(1,0)),...
    'failed_point_indices',fieldOr(c,'failed_point_indices',zeros(1,0)),...
    'attempt_count',numel(fieldOr(c,'attempts',[])),...
    'inserted_nodes_all_attempts',double(fieldOr(c,'inserted_nodes',0)),...
    'selected_path_count',double(fieldOr(c,'selected_path_count',0)),...
    'selected_path_added_nodes',double(fieldOr(c,'selected_path_added_nodes',0)),...
    'selected_path_min_positive_clearance_mm',double(fieldOr(c,'selected_path_min_positive_clearance_mm',NaN)),...
    'selected_path_max_joint_delta_deg',double(fieldOr(c,'selected_path_max_joint_delta_deg',NaN)),...
    'selected_path_max_tcp_error_mm',double(fieldOr(c,'selected_path_max_tcp_error_mm',NaN)),...
    'selected_path_edge_sample_count',double(fieldOr(c,'selected_path_edge_sample_count',0)),...
    'selected_level',double(fieldOr(c,'selected_level',0)),...
    'selected_fractions',fieldOr(c,'selected_fractions',zeros(1,0)),...
    'max_bridge_depth_budget',double(fieldOr(c,'max_bridge_depth_budget',NaN)),...
    'max_bridge_ik_budget',double(fieldOr(c,'max_bridge_ik_budget',NaN)),...
    'max_bridge_time_budget_sec',double(fieldOr(c,'max_bridge_time_budget_sec',NaN)),...
    'attempt_min_positive_clearance_mm',double(fieldOr(c,'attempt_min_positive_clearance_mm',NaN)),...
    'global_attempt_min_positive_clearance_mm',double(fieldOr(c,'min_positive_clearance_mm',NaN)),...
    'execution_ready',false);
if b.selected_path_count==0 && isfield(c,'attempts') && ~isempty(c.attempts)
    ok=[c.attempts.success];
    if any(ok)
        a=c.attempts(find(ok,1,'first'));
        b.selected_path_count=1; b.selected_path_added_nodes=double(a.added_nodes);
        b.selected_path_min_positive_clearance_mm=double(a.min_positive_clearance_mm);
        b.selected_path_max_joint_delta_deg=double(a.max_joint_delta_deg);
        b.selected_path_max_tcp_error_mm=double(a.max_tcp_error_mm);
        b.selected_path_edge_sample_count=double(a.edge_sample_count);
        b.selected_level=double(a.level);
        b.selected_fractions=double(a.fractions);
    end
end
if isempty(b.selected_fractions) && isfield(c,'attempts') && ~isempty(c.attempts)
    ok=[c.attempts.success];
    if any(ok)
        aa=c.attempts(ok);
        [~,jj]=min(abs([aa.min_positive_clearance_mm]-b.selected_path_min_positive_clearance_mm));
        b.selected_level=double(aa(jj).level);
        b.selected_fractions=double(aa(jj).fractions);
    end
end
if isfield(r,'options')
    if ~isfinite(b.max_bridge_depth_budget), b.max_bridge_depth_budget=double(fieldOr(r.options,'cartesianBridgeMaxDepth',NaN)); end
    if ~isfinite(b.max_bridge_ik_budget), b.max_bridge_ik_budget=double(fieldOr(r.options,'cartesianBridgeMaxIKCalls',NaN)); end
    if ~isfinite(b.max_bridge_time_budget_sec), b.max_bridge_time_budget_sec=double(fieldOr(r.options,'cartesianBridgeMaxTimeSec',NaN)); end
end
end

function t=localTimedSummary(r)
tp=fieldOr(r,'timeParameterization',struct());
cv=fieldOr(tp,'controllerInterpolationValidation',struct());
t=struct('complete',logical(fieldOr(cv,'complete',false)),'execution_ready',false,...
    'interpolation_mode',fieldOr(cv,'interpolation_mode','UNKNOWN'),...
    'sample_count',double(fieldOr(cv,'sample_count',0)),...
    'duration_sec',double(fieldOr(cv,'duration_sec',fieldOr(tp,'durationSec',NaN))),...
    'max_tcp_contour_error_mm',double(fieldOr(cv,'max_tcp_contour_error_mm',fieldOr(tp,'tcpContourMaxMm',NaN))),...
    'max_tcp_time_sync_error_mm',double(fieldOr(cv,'max_tcp_time_sync_error_mm',fieldOr(tp,'timeSyncMaxMm',NaN))),...
    'rms_tcp_time_sync_error_mm',double(fieldOr(cv,'rms_tcp_time_sync_error_mm',fieldOr(tp,'timeSyncRmsMm',NaN))),...
    'max_tcp_orientation_error_deg',double(fieldOr(cv,'max_tcp_orientation_error_deg',fieldOr(tp,'maxOrientationErrorDeg',NaN))),...
    'max_joint_velocity_rad_per_sec',double(fieldOr(cv,'max_joint_velocity_rad_per_sec',fieldOr(tp,'maxVelocityRadPerSec',NaN))),...
    'max_joint_acceleration_rad_per_sec2',double(fieldOr(cv,'max_joint_acceleration_rad_per_sec2',fieldOr(tp,'maxAccelerationRadPerSec2',NaN))),...
    'collision_pass',logical(fieldOr(cv,'collision_pass',fieldOr(tp,'collisionPass',false))),...
    'joint_limits_pass',logical(fieldOr(cv,'joint_limits_pass',fieldOr(tp,'jointLimitsPass',false))),...
    'min_positive_clearance_mm',double(fieldOr(cv,'min_positive_clearance_mm',NaN)),...
    'failure_reason',fieldOr(cv,'failureReason',fieldOr(tp,'failureReason','')),...
    'wire_collision_shorten_mm',double(fieldOr(fieldOr(r,'options',struct('wire_collision_shorten_mm',NaN)),'wire_collision_shorten_mm',NaN)));
end

function v=fieldOr(s,n,d)
if isstruct(s)&&isfield(s,n), v=s.(n); else, v=d; end
end

function s=localText(x)
if isempty(x)||~isfinite(double(x)), s='none'; else, s=num2str(x); end
end

function s=localCsv(x)
if isempty(x)||~isfinite(double(x)), s=''; else, s=sprintf('%.9f',double(x)); end
end
