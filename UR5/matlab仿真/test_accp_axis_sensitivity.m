function report=test_accp_axis_sensitivity(outputDir)
% Explicit REAL scene, cold runs, diagnostic artifacts only; no ROS motion.
here=fileparts(mfilename('fullpath'));
if nargin<1
    outputDir=fullfile(fileparts(here),'planning_runs', ...
        ['accp_axis_sensitivity_' datestr(now,'yyyymmdd_HHMMSSFFF')]);
end
if ~isfolder(outputDir), mkdir(outputDir); end
rows=cell(1,5); angles=[5 10 15 20 30];
for i=1:numel(angles)
    angle=angles(i); runDir=fullfile(outputDir,sprintf('tolerance_%02d',angle));
    if ~isfolder(runDir), mkdir(runDir); end
    opts=struct('sceneScript',fullfile(here,'sync_ur5_real_scene.m'), ...
        'numPoints',16,'randomSeed',20260917,'beamWidth',1,'firstPointMaxStates',2, ...
        'maxPoseSeeds',3,'coarseTravelDeg',[-15 0 15],'numRandomSeedsFirstPoint',10, ...
        'candidate_scoring_mode',true,'candidate_diagnostics',true, ...
        'axis_angle_tolerance_deg',angle,'disableAxisConstraint',false, ...
        'checkSelfCollision',true,'enableFallback',false,'animate',false,'publish',false, ...
        'configurationOnlyDiagnostic',true, ...
        'outputFile',fullfile(runDir,'diagnostic_core.mat'));
    r=replan_weld_actual_axis_adaptive_core(opts);
    assert(r.scene.realTcpLoaded && r.scene.realWorkpieceLoaded,'REAL calibration not loaded');
    assert(r.scene.realGunComponentCount>0 && r.scene.wireCollisionEnabled && ...
        ~isempty(r.scene.environment),'Required collision geometry missing');
    assert(r.options.checkSelfCollision && ~r.options.disableAxisConstraint);
    d=r.firstPointDiagnostics; audit=r.candidateSelectionDiagnostics{1};
    collisionsPassed=sum(strcmp(string({d.candidates.rejection_reason}),'accepted'));
    row=struct('axis_angle_tolerance_deg',angle,'ik_numeric_success',d.ik_numeric_success, ...
        'ik_success',d.ik_success,'axis_pass',d.ik_success-d.orientation_direction_rejected, ...
        'collision_pass_raw',collisionsPassed,'final_candidates',audit.connected_candidate_count, ...
        'retained_candidates',numel(r.stateBank{1}),'all_16_pass', ...
        logical(r.configurationComplete && r.configurationNodeCollisionFree && r.configurationEdgeCollisionFree), ...
        'furthest_point',find(~cellfun(@isempty,r.stateBank),1,'last'), ...
        'planning_time_sec',r.algorithmElapsedSec,'filter_counts',rmfield(d,'candidates'), ...
        'calibration_binding',r.scene.calibrationBinding,'collision_workpiece',true, ...
        'collision_gun',true,'collision_wire',true,'axis_constraint',true, ...
        'max_segment_tcp_error_mm',r.tcpMetrics.maxSegmentPositionErrorMm);
    if isempty(row.furthest_point), row.furthest_point=0; end
    rows{i}=row;
    writeJson(fullfile(runDir,'point1_diagnostics.json'),d);
    fprintf('SENSITIVITY %2d deg: IK=%d axis=%d collision=%d unique=%d 16PASS=%d\n', ...
        angle,row.ik_success,row.axis_pass,row.collision_pass_raw,row.final_candidates,row.all_16_pass);
end
report=struct('schema_version','ACCP_AXIS_SENSITIVITY_v1','robot_motion','NO', ...
    'scene_script',fullfile(here,'sync_ur5_real_scene.m'),'seed',20260917, ...
    'description','Identical cold-search settings. IK success includes pose/limit checks; collision counts include duplicate seed hits; final candidates deduplicated before beam pruning. PASS is discrete core node/edge feasibility, not execution clearance.', ...
    'results',{rows});
writeJson(fullfile(outputDir,'comparison.json'),report);
fid=fopen(fullfile(outputDir,'comparison.csv'),'w');
if fid<0, error('Cannot write CSV'); end
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'axis_deg,ik_success,axis_pass,collision_pass_raw,final_candidates,retained,all_16_pass,furthest_point,planning_time_sec\n');
for i=1:numel(rows)
    x=rows{i}; fprintf(fid,'%g,%d,%d,%d,%d,%d,%d,%d,%.6f\n', ...
        x.axis_angle_tolerance_deg,x.ik_success,x.axis_pass,x.collision_pass_raw, ...
        x.final_candidates,x.retained_candidates,x.all_16_pass,x.furthest_point,x.planning_time_sec);
end
end

function writeJson(path,data)
fid=fopen(path,'w'); if fid<0, error('Cannot write %s',path); end
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(data,'PrettyPrint',true));
end
