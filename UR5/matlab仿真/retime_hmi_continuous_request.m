function report=retime_hmi_continuous_request(request)
% Revalidate a slower copy of an already completed offline trajectory.
% No path search, IK, geometry edits, ROS calls or execution authorization.
here=fileparts(mfilename('fullpath')); addpath(here,'-end');
out=char(request.outputDir); if ~isfolder(out), mkdir(out); end
report=struct('executionReady',false,'success',false,'robot_motion','NO',...
    'task','Full_Welding_Task','algorithm','CBi-RRT* + ACCP-D','preview_preserved',true,...
    'stage','INPUT_VALIDATION','continuous_planning_complete',false,...
    'continuous_planning_status','CONTINUOUS_PLANNING','physical_validation_status','PENDING',...
    'servo_validation_status','PENDING','architecture_version','THREE_STAGE_CONTINUOUS_v1',...
    'stage_timings',struct());
timer=tic;
try
    clock=tic;
    collisionDir=fullfile(fileparts(fileparts(here)),'RRT');
    collisionHelper=fullfile(collisionDir,'checkEnvironmentCollision.m');
    assert(isfile(collisionHelper),'CONTINUOUS:Dependency','Missing collision adapter');
    addpath(collisionDir,'-end');
    assert(strcmp(which('checkEnvironmentCollision'),collisionHelper),...
        'CONTINUOUS:Dependency','Unexpected collision adapter');
    checkSources(request);
    originalRequest=jsondecode(fileread(request.sourceRequest));
    assert(strcmp(originalRequest.rawFile,request.rawFile) && ...
        strcmp(originalRequest.raw_sha256,request.raw_sha256),...
        'RETIME:Stale','Source request points to a different preview');
    old=jsondecode(fileread(request.sourceReport)); source=load(request.sourceFile);
    assert(old.success && old.continuous_planning_complete && ~old.executionReady && ...
        strcmp(old.continuous_planning_status,'PASS') && old.controller_validation.complete && ...
        old.controller_validation.collision_pass && old.controller_validation.analytic_extrema_pass && ...
        all(structfun(@(v)islogical(v)&&isscalar(v)&&v,old.offline_checks)),...
        'RETIME:Source','Source is not a completed offline trajectory');
    assert(strcmp(source.metadata.workflow_stage,'PHYSICAL_VALIDATION_PENDING') && ...
        source.metadata.preview_only && source.metadata.diagnostic_only && ~source.metadata.executionReady,...
        'RETIME:Source','Only offline validated P+V trajectories may be retimed');
    assert(strcmp(hmi_workflow_file_hash(old.artifacts.trajectory_mat),request.source_sha256) && ...
        strcmp(hmi_workflow_file_hash(old.artifacts.trajectory_json),request.source_json_sha256),...
        'RETIME:Source','Source report/reference does not match source MAT');
    j=jsondecode(fileread(old.artifacts.trajectory_json));
    assert(isequal(size(j.qPath),size(source.qPath)) && ...
        max(abs(j.qPath-source.qPath),[],'all')<2e-14 && ...
        max(abs(j.timeFromStart(:)-source.timeFromStart(:)))<2e-14 && ...
        max(abs(j.velocities-source.velocities),[],'all')<2e-14,...
        'RETIME:Source','Source numeric data differs from its validated JSON');
    raw=load(request.rawFile);
    assert(raw.metadata.preview_only && numel(raw.segments)==3 && ...
        strcmp(raw.metadata.realhome_version,source.metadata.realhome_version),...
        'RETIME:Stale','Source Home or preview mismatch');
    assert(strcmp(hmi_workflow_file_hash(raw.sceneFile),raw.metadata.scene_snapshot_sha256),...
        'RETIME:Stale','Scene snapshot changed');
    assert(isequaln(source.metadata.calibration_binding,old.version_validation.current_binding),...
        'RETIME:Stale','Source version evidence mismatch');
    x=load(raw.sceneFile,'scene'); scene=x.scene;
    scene.hmiMotionLimits=hmi_load_robot_motion_limits(request.motion_limits_file,request.motion_limits_sha256);
    report.motion_limits=scene.hmiMotionLimits;
    assert(strcmp(old.motion_limits.profile_sha256,report.motion_limits.profile_sha256),...
        'RETIME:Stale','Source motion-limit profile changed');
    report.realhome_version=source.metadata.realhome_version;
    candidate=struct('qPath',source.qPath,'tcpPosePath',{source.tcpPosePath},...
        'timeFromStart',source.timeFromStart(:),'velocities',source.velocities,...
        'segmentLabel',{source.segmentLabel},'pathTimeReference',source.metadata.path_time_reference);
    weld=raw.segments{2}; assert(size(weld.qPath,1)==47,'RETIME:Weld','Expected 47 original weld nodes');
    [present,map]=ismember(weld.qPath,candidate.qPath,'rows');
    assert(all(present) && all(diff(map)>0) && ...
        isequal(reshape(candidate.tcpPosePath(map),1,[]),reshape(weld.tcpPosePath,1,[])),...
        'RETIME:Weld','Original ACCP q/TCP targets changed or missing');
    candidate.joins=[map(1),map(end)];
    assert(all(candidate.joins>1 & candidate.joins<size(source.qPath,1)),...
        'RETIME:Boundary','Invalid approach/weld/exit boundaries');
    report.stage_timings.input_sec=toc(clock);
    report.stage='OFFLINE_TIME_SCALING'; fprintf('HMI_WELD_STAGE stage=OFFLINE_TIME_SCALING\n'); clock=tic;
    [candidate,scaling]=hmi_scale_continuous_candidate(candidate,request.offline_speed_percent);
    scaling.source_trajectory=request.sourceFile; scaling.source_sha256=request.source_sha256;
    scaling.source_report_sha256=request.source_report_sha256;
    report.offline_speed_scaling=scaling;
    dm=scaling.derivatives; limits=hmi_scene_motion_limits(scene); lim=scene.jointLimits;
    c2=all(abs(dm.node_acceleration_jump(candidate.joins-1,:))<1e-6,'all');
    rest=max(abs([candidate.velocities(1,:),candidate.velocities(end,:),...
        dm.acceleration_start(1,:),dm.acceleration_end(end,:)]))<1e-8;
    analytic=dm.max_velocity<=limits.velocityLimit && dm.max_acceleration<=limits.accelerationLimit && ...
        all(dm.position_min>=lim(:,1).') && all(dm.position_max<=lim(:,2).');
    report.velocity_optimization=struct('pass',c2 && rest && analytic,'derivatives',dm,...
        'interface_c2_optimization',struct('pass',c2),'method',scaling.method,'inserted_execution_nodes',0);
    report.boundaries_after=struct('velocity_jump',0,...
        'acceleration_jumps',dm.node_acceleration_jump(candidate.joins-1,:));
    report.geometry_consistency=struct('pass',true,'method','FROZEN_SOURCE_NODES_AND_HERMITE_COEFFICIENTS',...
        'original_weld_nodes_preserved',47,'q_nodes_unchanged',true,'TCP_targets_unchanged',true);
    report.original_path_nodes_preserved=true; report.original_weld_nodes_preserved=47;
    report.stage_timings.parameterization_sec=toc(clock);
    report=hmi_continuous_acceptance(candidate,raw,scene,request,report);
    assert(report.final_acceptance_pass,'RETIME:Acceptance','%s: %s',...
        field(report,'acceptance_failure_identifier',''),field(report,'acceptance_failure_reason',''));
    checkSources(request); % Source changes during the dense audit fail closed.
    report.stage='OFFLINE_ARTIFACT_EXPORT'; clock=tic;
    report=hmi_export_offline_continuous_result(candidate,report,raw,report.current_binding,out,scene);
    report.stage_timings.offline_export_sec=toc(clock);
catch err
    report.executionReady=false; report.success=false; report.failure_reason=err.message;
    report.continuous_planning_complete=false; report.continuous_planning_status='CONTINUOUS_PLANNING_FAILED';
    report.failed_stage=report.stage; report.stage='CONTINUOUS_PLANNING_FAILED';
    report.failure_identifier=err.identifier; report.failure_stack=err.stack;
    fprintf('CONTINUOUS_PLANNING_FAILED %s\n',err.message);
end
report.planning_time=toc(timer);
fid=fopen(fullfile(out,'report.json'),'w'); assert(fid>=0); cleanup=onCleanup(@()fclose(fid));
fwrite(fid,jsonencode(report,'PrettyPrint',true),'char');
end
function checkSources(r)
for pair={'sourceFile','source_sha256';'sourceReport','source_report_sha256';...
          'sourceRequest','source_request_sha256';'rawFile','raw_sha256'}.'
    assert(strcmp(hmi_workflow_file_hash(r.(pair{1})),r.(pair{2})),...
        'RETIME:Stale','Source file changed: %s',r.(pair{1}));
end
end
function v=field(s,key,default)
if isfield(s,key), v=s.(key); else, v=default; end
end
