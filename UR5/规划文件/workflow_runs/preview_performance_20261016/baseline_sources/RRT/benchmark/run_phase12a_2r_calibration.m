function report = run_phase12a_2r_calibration(options)
%run_phase12a_2r_calibration Seam A collision-resolution calibration.
%
% Runs only:
%   T01: qSafe(qHome) -> Point 1
%   T02: Point 80 -> qSafe(qHome)
% with 5 matched seeds and the common 2 s wall-clock planner limit.
% This is 2 tasks x 4 algorithms x 5 seeds = 40 runs.

if nargin < 1 || isempty(options), options=struct(); end
root=fileparts(fileparts(mfilename('fullpath')));
defaults=struct( ...
    'taskSet','seamA', ...
    'maxPlanningTimeSec',2.0, ...
    'maxIterations',300, ...
    'maxJointStepRad',deg2rad(25), ...
    'goalBias',0.20, ...
    'jointEdgeResolutionRad',deg2rad(0.25), ...
    'validationResolutionRad',deg2rad(0.125), ...
    'seeds',1:5, ...
    'bootstrapReplicates',1000, ...
    'outputFile',fullfile(root,'results','phase12a_2r_calibration_40.mat'), ...
    'rawCsvFile',fullfile(root,'results','phase12a_2r_calibration_40_runs.csv'), ...
    'summaryCsvFile',fullfile(root,'results','phase12a_2r_calibration_40_summary.csv'), ...
    'figureDir',fullfile(root,'results','phase12a_2r_calibration_40_figures'), ...
    'saveResult',true);
options=mergeLocal(defaults,options);
report=run_phase12a_pilot(options);
fprintf('PHASE12A2R_CALIBRATION_DONE rows=%d plannerSuccess=%d validSuccess=%d timeouts=%d\n', ...
    report.completedRuns,sum([report.rows.success]), ...
    sum([report.rows.finalValidationPass]),sum([report.rows.plannerTimedOut]));
end

function out=mergeLocal(defaults,in)
out=defaults;
names=fieldnames(defaults);
for i=1:numel(names)
    if isfield(in,names{i}) && ~isempty(in.(names{i}))
        out.(names{i})=in.(names{i});
    end
end
end
