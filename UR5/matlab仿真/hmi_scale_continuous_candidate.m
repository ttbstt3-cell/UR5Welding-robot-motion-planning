function [candidate,info]=hmi_scale_continuous_candidate(candidate,percent)
% Uniform offline time dilation. Never changes q, TCP, geometry or limits.
assert(isnumeric(percent) && isscalar(percent) && isfinite(percent) && ...
    percent>=1 && percent<=100,'RETIME:Percent','Offline speed must be 1..100 percent');
factor=double(percent)/100;
Q=candidate.qPath; P=candidate.tcpPosePath;
t=candidate.timeFromStart(:); V=candidate.velocities;
assert(size(Q,2)==6 && isequal(size(Q),size(V)) && numel(t)==size(Q,1) && ...
    all(isfinite([Q(:);V(:);t])) && t(1)==0 && all(diff(t)>0),...
    'RETIME:Input','Requires finite positions + velocities and increasing timestamps');
ref=candidate.pathTimeReference;
assert(strcmp(ref.mode,'FROZEN_CARTESIAN_PATH_MONOTONE_LOCAL_CLOCK_v2') && ...
    isequal(ref.clockTimes(:),t) && ref.duration==t(end),...
    'RETIME:Reference','Independent Cartesian clock does not match source trajectory');
before=accp_cubic_derivative_metrics(Q,t,V);
candidate.timeFromStart=t/factor; candidate.velocities=V*factor;
ref.duration=candidate.timeFromStart(end); ref.clockTimes=candidate.timeFromStart;
candidate.pathTimeReference=ref;
candidate.executionReady=false; candidate.diagnostic_only=true;
after=accp_cubic_derivative_metrics(Q,candidate.timeFromStart,candidate.velocities);
assert(isequal(Q,candidate.qPath) && isequal(P,candidate.tcpPosePath),...
    'RETIME:Mutation','Immutable joint/TCP nodes changed');
% A Hermite edge depends on q0,q1,h*v0,h*v1. Check both endpoint products,
% not just node FK; this preserves the entire interpolated geometric curve.
h=diff(t); hs=diff(candidate.timeFromStart);
delta=[hs.*candidate.velocities(1:end-1,:)-h.*V(1:end-1,:);...
       hs.*candidate.velocities(2:end,:)-h.*V(2:end,:)];
assert(max(abs(delta),[],'all')<1e-11,'RETIME:Geometry','Hermite geometry changed');
info=struct('method','UNIFORM_OFFLINE_TIME_DILATION','percent_of_input',double(percent),...
    'speed_factor',factor,'time_multiplier',1/factor,'source_duration_sec',t(end),...
    'duration_sec',candidate.timeFromStart(end),'joint_nodes_unchanged',true,...
    'TCP_targets_unchanged',true,'hermite_coefficient_max_difference',max(abs(delta),[],'all'),...
    'baseline_derivatives',before,'derivatives',after,'executionReady',false,...
    'reference_clock_scaled_with_trajectory',true,...
    'note','Relative to this input only; not a runtime speed-slider command or physical validation');
end
