function report=test_confirmed_Areal_scene(outputFile)
% Read-only confirmed REAL scene loading and Saved RealHome collision check.
% No planning, robot connection, motion, or change to collision constraints.
scene=build_real_planning_scene(false);
q=reshape(scene.qMat0,1,6);
[self,~,~]=checkCollision(scene.robot,q,'IgnoreSelfCollision','off', ...
    'Exhaustive','on','SkippedSelfCollisions',scene.selfCollisionSkipPairs);
[env,~,~]=checkCollision(scene.robot,q,scene.environment, ...
    'IgnoreSelfCollision','on','Exhaustive','on');
report=struct('status','REAL_SCENE_LOADED','robot_motion','NO', ...
    'gun_active',scene.realGunGeometryActive,'gun_component_count',scene.realGunComponentCount, ...
    'wire_status',scene.realWireAxisStatus,'wire_collision_enabled',scene.wireCollisionEnabled, ...
    'wire_length_mm',scene.wireLengthM*1000,'wire_diameter_mm',scene.wireDiameterM*1000, ...
    'tcp_loaded',scene.realTcpLoaded,'tcp_authority',scene.realTcpAuthority, ...
    'workpiece_loaded',scene.realWorkpieceLoaded,'self_collision',any(self(:)), ...
    'environment_collision',any(env(:)),'old_trajectories_stale',true, ...
    'trajectory_planned',false,'execution_authorized',false);
fid=fopen(outputFile,'w'); cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
fwrite(fid,jsonencode(report),'char');
fprintf('CONFIRMED_REAL_SCENE components=%d wire=%s self=%d environment=%d motion=NO\n', ...
    scene.realGunComponentCount,scene.realWireAxisStatus,any(self(:)),any(env(:)));
end
